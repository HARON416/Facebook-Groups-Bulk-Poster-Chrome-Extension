			<h2>1. What Postika Is</h2>
			<p>
				Postika is a Chrome extension that helps you prepare and publish posts to Facebook Groups.
				No Postika account, sign-in, or remote Postika backend is required. The extension runs in
				Chrome and communicates directly with Facebook to load Groups and publish posts.
			</p>
			<p>
				The Postika website provides product information and this Privacy Policy. Publishing takes
				place through the Chrome extension and Facebook.
			</p>
			<p>
				Postika is an independent product. It is not affiliated with, endorsed by, sponsored by,
				or officially connected to Meta or Facebook.
			</p>

			<h2>2. Content You Choose to Publish</h2>
			<p>
				Post text is saved in Chrome extension storage on your device so your draft can be
				restored. When you start a queue, the extension sends the content you selected directly to
				Facebook. Postika does not upload or store this content on a remote Postika server.
			</p>

			<h2>3. Images</h2>
			<p>
				Selected images are saved in Chrome extension storage on your device so they can be
				restored with your draft. They are sent directly to Facebook for the post you requested;
				Postika does not upload or host them.
			</p>

			<h2>4. Facebook Information Processed in the Browser</h2>
			<p>
				Postika operates through the Facebook account already signed in to the active Chrome
				profile. Depending on the feature you start, the extension processes:
			</p>
			<ul>
				<li>
					Joined Group identifiers, names, URLs, join state, last-visited information when
					available, and your Group selections.
				</li>
				<li>The post text and images you select for a Group publishing queue.</li>
				<li>
					Facebook request URLs, headers, request bodies, form fields, and response data needed to
					load Groups and carry out the posting queue you started.
				</li>
				<li>
					Facebook cookie names and request-cookie availability used for local diagnostics. For a
					publishing workflow, the extension reads the numeric <code>c_user</code> Facebook account
					identifier locally to verify the active account. It does not send that identifier or other
					Facebook cookie values to a Postika server.
				</li>
			</ul>
			<p>
				This Facebook workflow information and captured request templates are processed inside the
				browser and sent to Facebook to perform the action you requested. Postika does not store
				Facebook passwords, Facebook cookie values, or captured Facebook request templates on a
				Postika server.
			</p>
			<p>
				When a Group post fails, Postika may temporarily display Facebook's response body in the
				current activity log so you can copy it for troubleshooting. The response remains in the
				current extension session, is not uploaded to a Postika server, and is copied only when
				you press the copy button.
			</p>
			<p>
				Content published to Facebook is received and handled by Facebook under Facebook’s own
				terms and privacy practices.
			</p>

			<h2>5. Information Stored in Chrome</h2>
			<p>The extension stores the following information in Chrome extension storage:</p>
			<ul>
				<li>
					Loaded Group information, selected Group identifiers, Group search text, and display
					preferences.
				</li>
				<li>
					During the current browser session, a SHA-256 key representing the active Facebook account
					and Group identifiers that could not initialize the first visible composer, so the current
					or a later queue can automatically choose another starter Group.
				</li>
				<li>
					Group queue intervals, posting preferences, group selections, and other current
					side-panel workflow settings.
				</li>
				<li>The current post body and selected image files.</li>
			</ul>
			<p>
				Clearing extension data or uninstalling Postika removes this locally stored information.
				Content already published on Facebook is not removed.
			</p>

			<h2>6. Browser-Only Draft Storage</h2>
			<p>
				Drafts, images, Groups, and workflow preferences remain in Chrome extension storage on
				your device. The extension does not send them to a Postika backend. Chrome may limit
				extension storage; if a draft cannot be saved, Postika reports that in the extension.
			</p>

			<h2>7. Posting Limits</h2>
			<p>
				Postika does not assign account tiers or enforce per-account storage or daily posting
				quotas. It does not create posting reservations or store usage records to enforce a quota.
				Facebook’s own posting limits, policies, and Group rules still apply.
			</p>

			<h2>8. When Information Is Shared</h2>
			<p>Postika transfers information only as needed for the current product flow:</p>
			<ul>
				<li>
					<strong>Facebook:</strong> to load available Groups and perform publishing actions that
					you start.
				</li>
				<li>
					<strong>Website hosting providers:</strong> to serve the Postika product information and
					Privacy Policy.
				</li>
			</ul>
			<p>
				Postika does not sell personal information and does not use extension data for
				personalized, retargeted, or interest-based advertising.
			</p>

			<h2>9. Retention and Deletion</h2>
			<p>
				Postika does not create user accounts or store extension posting data on a remote Postika
				server. Extension data remains in Chrome until you clear it or uninstall the extension.
				Data sent to Facebook is handled under Facebook’s terms and privacy policy.
			</p>

			<h2>10. Your Controls</h2>
			<ul>
				<li>Review and edit content before publishing it.</li>
				<li>Choose the post, Groups, and timing for each workflow.</li>
				<li>Pause, resume, or stop an active publishing queue.</li>
				<li>Clear extension storage or uninstall Postika to remove local extension data.</li>
			</ul>

			<h2>11. Chrome Web Store Data Policy</h2>
			<p>
				Information obtained through Chrome extension permissions is used only to provide and
				improve Postika’s disclosed user-facing features. It is not used for personalized
				advertising, creditworthiness, lending, or unrelated profiling.
			</p>
			<p>Postika follows the Chrome Web Store User Data Policy for data handled by the extension.</p>

			<h2>12. Security</h2>
			<p>
				Postika keeps workflow data in Chrome and sends information to Facebook only when needed
				for the action you request. No transmission or storage method can guarantee absolute
				security.
			</p>

